import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:kids_app/media/audio_manifest.dart';
import 'package:kids_app/media/audio_status.dart';

/// Builds docs/AUDIO_COVERAGE.md from the REAL manifest (what the app would play today). It never invents numbers:
/// run with WRITE_AUDIO_REPORT=1 to rewrite the file, otherwise the test only checks the numbers add up.
String buildCoverageReport(AudioManifest m, {required bool deviceVoice}) {
  final items = statusesOf(m, deviceVoiceEnabled: deviceVoice);
  final b = StringBuffer()
    ..writeln('# Audio coverage (generated from the real manifest)')
    ..writeln()
    ..writeln('Generated by `test/audio_coverage_report_test.dart` (run with `WRITE_AUDIO_REPORT=1 flutter test test/audio_coverage_report_test.dart`).')
    ..writeln('Content-quality statuses only: nothing here says a pronunciation was checked by a machine.')
    ..writeln()
    ..writeln('Device voice allowed in this report: **${deviceVoice ? 'yes' : 'no'}** (the app default is yes).')
    ..writeln();
  final all = summarize(items);
  b
    ..writeln('## Totals')
    ..writeln()
    ..writeln('| Measure | Count |')
    ..writeln('|---|---:|')
    ..writeln('| Audio items the content needs | ${all.total} |')
    ..writeln('| Bundled audio files that exist | ${all.filesExisting} |')
    ..writeln('| Approved (file + license + audio review + language review) | ${all.approved} |')
    ..writeln('| A file exists but is not approved (children do not hear it) | ${all.needsReview} |')
    ..writeln('| Child would hear an approved human recording | ${all.recorded} |')
    ..writeln('| Child would hear an approved synthetic file | ${all.syntheticFile} |')
    ..writeln('| Child would hear the device demo voice | ${all.deviceVoice} |')
    ..writeln('| Nothing can be played (message + text on screen) | ${all.none} |')
    ..writeln();
  for (final lang in ['ar', 'en']) {
    final mine = items.where((s) => s.asset.lang == lang).toList();
    final sum = summarize(mine);
    b
      ..writeln('## ${lang == 'ar' ? 'Arabic' : 'English'} (${sum.total} items)')
      ..writeln()
      ..writeln('| Kind | Items | Files | Approved | Device voice | Nothing |')
      ..writeln('|---|---:|---:|---:|---:|---:|');
    for (final k in AudioKind.values) {
      final ks = mine.where((s) => s.asset.kind == k).toList();
      if (ks.isEmpty) continue;
      final ksum = summarize(ks);
      b.writeln('| ${k.name} | ${ksum.total} | ${ksum.filesExisting} | ${ksum.approved} | ${ksum.deviceVoice} | ${ksum.none} |');
    }
    b.writeln();
  }
  final statuses = <AssetStatus, int>{};
  for (final a in m.all) {
    statuses[a.status] = (statuses[a.status] ?? 0) + 1;
  }
  b
    ..writeln('## By review status')
    ..writeln()
    ..writeln('| Status | Items |')
    ..writeln('|---|---:|');
  for (final e in statuses.entries) {
    b.writeln('| ${e.key.name} | ${e.value} |');
  }
  b
    ..writeln()
    ..writeln('Isolated letter sounds and phonics (${items.where((s) => !s.asset.deviceVoiceAllowed).length} items) can NEVER be read by the device')
    ..writeln('voice; until an approved recording exists they stay silent and the screen says so.');
  return b.toString();
}

void main() {
  test('the coverage numbers add up and match the rules of the audio service', () {
    final m = AudioManifest.builtIn();
    final on = summarize(statusesOf(m, deviceVoiceEnabled: true));
    final off = summarize(statusesOf(m, deviceVoiceEnabled: false));
    expect(on.total, m.all.length);
    expect(on.recorded + on.syntheticFile + on.deviceVoice + on.none, on.total);
    expect(off.deviceVoice, 0);
    expect(on.approved, m.approvedCount);
    expect(on.filesExisting >= on.approved, true);
    // nothing is approved without evidence (see AudioAsset.approved)
    expect(m.validate(), isEmpty);
  });

  test('write the report when asked', () {
    if (Platform.environment['WRITE_AUDIO_REPORT'] != '1') return;
    final m = AudioManifest.builtIn();
    final off = summarize(statusesOf(m, deviceVoiceEnabled: false));
    final text = '${buildCoverageReport(m, deviceVoice: true)}\n'
        '## If a parent switches the device demo voice off\n\n'
        'Only approved recordings would play: **${off.recorded + off.syntheticFile}** of ${off.total} items; the other ${off.none} stay silent with a message and the text on screen.\n';
    File('docs/AUDIO_COVERAGE.md').writeAsStringSync(text);
  });
}
