// node build.mjs -> game_src/<game>/src/samples.js from src/<game>/*.mp3 (trimmed to the pack's duration, mono 32 kHz 48 kbps) and hooks it into the game's audio.js
import fs from 'node:fs'; import path from 'node:path'; import { execFileSync } from 'node:child_process'; import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url)); const root = path.join(dir, '..', '..', 'game_src');
const packs = JSON.parse(fs.readFileSync(path.join(dir, 'packs.json'), 'utf8'));
for (const [g, p] of Object.entries(packs)) {
  const out = []; let bytes = 0;
  for (const [n, [, dur]] of Object.entries(p.clips)) {
    const f = path.join(dir, 'src', g, n + '.mp3'); if (!fs.existsSync(f)) continue;
    const tmp = path.join(dir, '_t.mp3'); const d = Math.min(dur + 0.2, 3.7);
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', f, '-t', String(d), '-af', `afade=t=out:st=${Math.max(0, d - 0.12)}:d=0.12`, '-ac', '1', '-ar', '32000', '-b:a', '48k', tmp]);
    const b = fs.readFileSync(tmp); bytes += b.length; out.push(`  ${n}: 'data:audio/mpeg;base64,${b.toString('base64')}',`); fs.unlinkSync(tmp);
  }
  if (!out.length) continue;
  const sf = path.join(root, g, 'src', 'samples.js'); fs.writeFileSync(sf, `// generated by tools/game_sfx/build.mjs (ElevenLabs sound generation) - do not edit\nexport const SAMPLES = {\n${out.join('\n')}\n};\n`);
  const af = path.join(root, g, 'src', 'audio.js'); let s = fs.readFileSync(af, 'utf8');
  if (!s.includes('attachSamples')) {
    const cls = /export class (\w+)/.exec(s)[1];
    s = `import { attachSamples } from '../../cozy_kit/sample_hook.js';\nimport { SAMPLES } from './samples.js';\n` + s + `\nattachSamples(${cls}, SAMPLES);\n`; fs.writeFileSync(af, s);
  }
  console.log(g, out.length, 'clips', Math.round(bytes / 1024) + ' KB');
}

// ---- songs: src/<game>/_music.mp3 -> assets/games/<game>/music.mp3 + attachMusic in audio.js
const music = JSON.parse(fs.readFileSync(path.join(dir, 'music.json'), 'utf8'));
for (const g of Object.keys(music)) {
  const f = path.join(dir, 'src', g, '_music.mp3'); const af = path.join(root, g, 'src', 'audio.js'); if (!fs.existsSync(f) || !fs.existsSync(af)) continue;
  const out = path.join(root, '..', 'assets', 'games', g, 'music.mp3');
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', f, '-t', '20', '-af', 'afade=t=in:d=0.05,afade=t=out:st=19.7:d=0.3', '-ac', '2', '-ar', '32000', '-b:a', '80k', out]);
  let s = fs.readFileSync(af, 'utf8');
  if (!s.includes('attachMusic')) {
    if (s.includes("import { attachSamples } from")) s = s.replace("import { attachSamples } from", "import { attachSamples, attachMusic } from");
    else s = `import { attachMusic } from '../../cozy_kit/sample_hook.js';
` + s;
    const cls = /export class (\w+)/.exec(s)[1]; s += `attachMusic(${cls});
`; fs.writeFileSync(af, s);
  }
  console.log(g, 'music', Math.round(fs.statSync(out).size / 1024) + ' KB');
}
