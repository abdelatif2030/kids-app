COLORABLE = {'الدايرة', 'المربع', 'المثلث', 'النجمة', 'القلب', 'المثمن', 'الهلال', 'علامة الجمع', 'الهرم'}


def add(M):
    def put(plain, dia):
        if plain not in M:
            M[plain] = dia
    for the, ar, fem in SHAPES:
        put('فين %s؟' % the, 'فِين %s؟' % THE[the])
        put(('دي ' if fem else 'ده ') + ar, ('دِي ' if fem else 'دَه ') + AR[ar])
        if the in COLORABLE:
            for m, f in zip(ADJ_M, ADJ_F):
                w = f if fem else m
                d = ADJ_F[f] if fem else ADJ_M[m]
                put('فين %s ال%s؟' % (the, w), 'فِين %s ال%s؟' % (THE[the], d))
                put(('دي ' if fem else 'ده ') + ar + ' ' + w, ('دِي ' if fem else 'دَه ') + AR[ar] + ' ' + d)
    for w, d in SIDES.items():
        put('فين الشكل اللي له %s أضلاع؟' % w, 'فِين الشَّكْل اللِّي لُه %s أَضْلَاع؟' % d)
