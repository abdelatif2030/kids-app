def add(M):
    HK = [('فتحة', 'فَتْحَة'), ('ضمة', 'ضَمَّة'), ('كسرة', 'كَسْرَة')]
    for the, thed in LETTER_THE.values():
        for w, d in HK:
            M.setdefault('فين حرف %s اللي عليه %s؟' % (the, w), 'فِين حَرْف %s اللِّي عَلَيْه %s؟' % (thed, d))
    for k, v in HABITS2:
        M.setdefault(k, v)
    for the, thed in VEHICLES2:
        M.setdefault('فين %s؟' % the, 'فِين %s؟' % thed)
    for the, thed, fem, food, foodd in ANIMALS:
        if fem:
            M['%s جعانة! هتاكل إيه؟' % the] = '%s جَعَانَة! هَتَاكُل إِيه؟' % thed
            M['%s بتحب %s' % (the, food)] = '%s بِتْحِبّ %s' % (thed, foodd)
        else:
            M['%s جعان! هياكل إيه؟' % the] = '%s جَعَان! هَيَاكُل إِيه؟' % thed
            M['%s بيحب %s' % (the, food)] = '%s بِيحِبّ %s' % (thed, foodd)
    for k, v in PICKS + HABITS:
        M[k] = v
    for w in MORE:
        the, thed = LETTER_THE[w['letter']]
        M['فين %s؟' % w['the']] = 'فِين %s؟' % w['thed']
        M['إيه الحرف الأول في كلمة %s؟' % w['word']] = 'إِيه الحَرْف الأَوَّل فِي كَلِمَة %s؟' % w['wd']
        M['%s زي %s' % (the, w['word'])] = '%s زَي %s' % (thed, w['wd'])
