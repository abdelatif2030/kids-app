import re
_strip = lambda t: re.sub('[ً-ْـٰ]', '', t)


def _fix(k, v):
    # the reading keeps the on-screen spelling: a word written with ة stays with ة (the marks are what the voice reads)
    kw, vw = k.split(' '), v.split(' ')
    if len(kw) != len(vw):
        return v
    out = []
    for a, b in zip(kw, vw):
        tail = '؟' if a.endswith('؟') else ''
        a2, b2 = a.rstrip('؟'), b.rstrip('؟')
        if a2.endswith('ة') and _strip(b2).endswith('ه') and _strip(b2)[:-1] == a2[:-1]:
            b = (b2[:-1] + 'ة' if b2[-1] == 'ه' else b2[:-2] + 'ة' + b2[-1:]) + tail
        out.append(b)
    return ' '.join(out)


