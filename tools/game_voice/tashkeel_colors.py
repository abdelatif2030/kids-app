# Diacritized readings of the colour sentences (letters/colors.js allColorSentences): «فين اللون X؟» for the 14 new colours and
# «فين الحاجة اللي لونها X؟» for the ten colours that have pictures. The 11 older «فين اللون ...» keep their earlier readings.
BARE = {
    'أحمر': 'أَحْمَر', 'أزرق': 'أَزْرَق', 'أصفر': 'أَصْفَر', 'أخضر': 'أَخْضَر', 'برتقالي': 'بُرْتُقَالِي', 'بنفسجي': 'بَنَفْسَجِي',
    'وردي': 'وَرْدِي', 'أسود': 'أَسْوَد', 'أبيض': 'أَبْيَض', 'بني': 'بُنِّي', 'رمادي': 'رَمَادِي',
}
THE = {
    'السماوي': 'السَّمَاوِي', 'الكحلي': 'الكُحْلِي', 'الأخضر الفاتح': 'الأَخْضَر الفَاتِح', 'الأخضر الغامق': 'الأَخْضَر الغَامِق',
    'التركواز': 'التُّرْكُوَاز', 'الذهبي': 'الدَّهَبِي', 'الفضي': 'الفِضِّي', 'البيج': 'البِيج', 'العنابي': 'العِنَّابِي',
    'الليموني': 'اللِّيمُونِي', 'الخوخي': 'الخَوْخِي', 'الليلكي': 'اللِّيلَكِي', 'الزيتي': 'الزَّيْتِي', 'الخردلي': 'الخَرْدَلِي',
}


def add(M):
    for plain, dia in THE.items():
        M.setdefault('فين اللون %s؟' % plain, 'فِين اللَّوْن %s؟' % dia)
    for plain, dia in BARE.items():
        M.setdefault('فين الحاجة اللي لونها %s؟' % plain, 'فِين الحَاجَة اللِّي لَوْنْهَا %s؟' % dia)
