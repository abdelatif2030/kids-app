#!/bin/bash
# Builds the girls world's sounds from the ElevenLabs sound-generation sources (*.src.mp3, made with the owner's key; prompts in README.md):
#  - short samples are trimmed, compressed and inlined as base64 into game_src/girls_games/src/kit/samples.js (they must work inside the app's webview too)
#  - the lullaby stays a file: assets/games/girls_world/snd/lullaby.mp3
cd "$(dirname "$0")"
OUT=../../game_src/girls_games/src/kit/samples.js
echo "// generated by tools/girls_sounds/build.sh - do not edit. base: the MIDI pitch of each sample (measured by pitch.mjs)" > $OUT
echo "export const SAMPLES = {" >> $OUT
for spec in "musicbox:1.3:87.72" "glock:1.3:83.25" "harp:1.4:61.12" "pop:0.6:0" "success:2.6:0" "sparkle:1.2:0"; do
  IFS=: read name dur base <<< "$spec"
  ffmpeg -v error -y -i $name.src.mp3 -t $dur -af "afade=t=out:st=$(python -c "print(max(0,$dur-0.15))"):d=0.15" -ac 1 -ar 32000 -b:a 56k _$name.mp3
  echo "  $name: { base: $base, data: 'data:audio/mpeg;base64,$(base64 -w0 _$name.mp3)' }," >> $OUT
  rm _$name.mp3
done
echo "};" >> $OUT
ffmpeg -v error -y -i lullaby.src.mp3 -ac 1 -ar 32000 -b:a 48k ../../assets/games/girls_world/snd/lullaby.mp3
ls -la ../../assets/games/girls_world/snd/lullaby.mp3 $OUT | awk '{print $5,$9}'
